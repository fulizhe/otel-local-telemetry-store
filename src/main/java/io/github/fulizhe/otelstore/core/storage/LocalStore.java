    public int countLogs() throws SQLException {
        return countRows("log_record");
    }

    /** metric_point 表行数。 */
    public int countMetrics() throws SQLException {
        return countRows("metric_point");
    }

    /** resource_dict 行数。 */
    public int countResources() throws SQLException {
        return resources.rowCount();
    }

    private int countRows(final String table) throws SQLException {
        synchronized (lock) {
            final PreparedStatement ps = conn.prepareStatement("SELECT COUNT(*) FROM " + table);
            try {
                final ResultSet rs = ps.executeQuery();
                try {
                    return rs.next() ? rs.getInt(1) : 0;
                } finally {
                    rs.close();
                }
            } finally {
                ps.close();
            }
        }
    }

    /**
     * 最近的 span 表头行（新到旧），不含载荷。
     *
     * <p>返回 {@code List<Map<String,Object>>} 而不是自定义行类型：读口要跨 ClassLoader
     * 交给 JMX / HTTP 侧序列化，只能出 JDK 原生类型（ADR-1 的读口约定）。
     */
    public List<Map<String, Object>> recentSpans(final int limit) throws SQLException {
        return query("SELECT id, trace_id, span_id, parent_span_id, name, kind, start_time, end_time,"
                        + " status_code, scope_name, scope_version, resource_id, attr_count, event_count,"
                        + " payload_id FROM span ORDER BY id DESC FETCH FIRST " + positive(limit) + " ROWS ONLY",
                SPAN_COLUMNS);
    }

    /** 某个 trace 的全部 span（按开始时间排），用来在详情页把一个 trace 拼起来。 */
    public List<Map<String, Object>> spansOfTrace(final String traceId) throws SQLException {
        final PreparedStatement ps;
        synchronized (lock) {
            ps = conn.prepareStatement("SELECT id, trace_id, span_id, parent_span_id, name, kind, start_time,"
                    + " end_time, status_code, scope_name, scope_version, resource_id, attr_count, event_count,"
                    + " payload_id FROM span WHERE trace_id = ? ORDER BY start_time ASC");
            try {
                ps.setString(1, traceId == null ? "" : traceId);
                return read(ps, SPAN_COLUMNS);
            } finally {
                ps.close();
            }
        }
    }

    /** 最近的日志表头行（新到旧），不含载荷。 */
    public List<Map<String, Object>> recentLogs(final int limit) throws SQLException {
        return query("SELECT id, trace_id, span_id, severity_number, severity_text, timestamp,"
                        + " body_preview, scope_name, scope_version, resource_id, attr_count, payload_id"
                        + " FROM log_record ORDER BY id DESC FETCH FIRST " + positive(limit) + " ROWS ONLY",
                LOG_COLUMNS);
    }

    /** 某个指标名最近的点（新到旧）。 */
    public List<Map<String, Object>> recentMetricPoints(final String metricName, final int limit)
            throws SQLException {
        final PreparedStatement ps;
        synchronized (lock) {
            ps = conn.prepareStatement("SELECT id, metric_name, data_type, ts, resource_id, scope_name,"
                    + " scope_version, attr_key, unit, metric_value, metric_count, metric_sum, detail"
                    + " FROM metric_point WHERE metric_name = ? ORDER BY ts DESC, id DESC FETCH FIRST "
                    + positive(limit) + " ROWS ONLY");
            try {
                ps.setString(1, metricName == null ? "" : metricName);
                return read(ps, METRIC_COLUMNS);
            } finally {
                ps.close();
            }
        }
    }

    /**
     * 按行 id 读回 span 的载荷。
     *
     * <p>{@code payload_id} 走 {@code wasNull()} 判定 —— 这是 ADR-2 第 1 条坑：
     * 载荷被拒写时这一列是 NULL，而 {@code 0} 恰好是合法的首个逻辑偏移。
     * 用 {@code getLong()} 的返回值判空会把"没有载荷"误报成"指向环里最老那块"，
     * 读回来的是一条**别人的**记录，且没有任何报错。
     *
     * @return 载荷字节；没有载荷或已被环覆盖时为 {@code null}（后者是<b>过期</b>，预期行为）
     */
    public byte[] spanPayload(final long spanId) throws SQLException {
        final long blockId;
        synchronized (lock) {
            final PreparedStatement ps = conn.prepareStatement("SELECT payload_id FROM span WHERE id = ?");
            try {
                ps.setLong(1, spanId);
                final ResultSet rs = ps.executeQuery();
                try {
                    if (!rs.next()) {
                        return null;
                    }
                    blockId = rs.getLong(1);
                    if (rs.wasNull()) {
                        return null;
                    }
                } finally {
                    rs.close();
                }
            } finally {
                ps.close();
            }
        }
        return traceRing.read(blockId);
    }

    /** 按行 id 读回日志记录的载荷；{@code payload_id} 的 NULL 判定同 {@link #spanPayload(long)}。 */
    public byte[] logPayload(final long logId) throws SQLException {
        final long blockId;
        synchronized (lock) {
            final PreparedStatement ps = conn.prepareStatement("SELECT payload_id FROM log_record WHERE id = ?");
            try {
                ps.setLong(1, logId);
                final ResultSet rs = ps.executeQuery();
                try {
                    if (!rs.next()) {
                        return null;
                    }
                    blockId = rs.getLong(1);
                    if (rs.wasNull()) {
                        return null;
                    }
                } finally {
                    rs.close();
                }
            } finally {
                ps.close();
            }
        }
        return logRing.read(blockId);
    }

    /** 读一份 Resource 的规范化文本（字典表那一列的原文）。 */
    public String resourceAttributes(final long resourceId) throws SQLException {
        synchronized (lock) {
            final PreparedStatement ps = conn.prepareStatement(
                    "SELECT attributes FROM resource_dict WHERE id = ?");
            try {
                ps.setLong(1, resourceId);
                final ResultSet rs = ps.executeQuery();
                try {
                    return rs.next() ? rs.getString(1) : null;
                } finally {
                    rs.close();
                }
            } finally {
                ps.close();
            }
        }
    }

    private List<Map<String, Object>> query(final String sql, final String[] columns) throws SQLException {
        synchronized (lock) {
            final PreparedStatement ps = conn.prepareStatement(sql);
            try {
                return read(ps, columns);
            } finally {
                ps.close();
            }
        }
    }

    /**
     * 把结果集摊成 JDK 原生 Map。
     *
     * <p>列名统一走 {@code getColumnLabel} 并转小写：H2 默认把未加引号的标识符折成大写，
     * 不统一的话读口那边会出现 {@code TRACE_ID} / {@code traceId} 两种命名。
     */
    private List<Map<String, Object>> read(final PreparedStatement ps, final String[] columns)
            throws SQLException {
        final List<Map<String, Object>> rows = new ArrayList<Map<String, Object>>();
        final ResultSet rs = ps.executeQuery();
        try {
            while (rs.next()) {
                final Map<String, Object> row = new LinkedHashMap<String, Object>();
                for (int i = 0; i < columns.length; i++) {
                    row.put(columns[i], rs.getObject(i + 1));
                }
                rows.add(row);
            }
        } finally {
            rs.close();
        }
        return rows;
    }

