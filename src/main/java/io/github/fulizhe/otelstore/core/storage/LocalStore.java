    @Override
    public void close() {
        synchronized (lock) {
            closeQuietly(traceRing);
            closeQuietly(logRing);
            try {
                conn.close();
            } catch (final SQLException e) {
                ThrottledLogger.warn("store-close", "关闭 H2 连接失败：" + e);
            }
        }
    }

    private static void closeQuietly(final Closeable c) {
        try {
            c.close();
        } catch (final IOException e) {
            ThrottledLogger.warn("ring-close", "关闭环形文件失败：" + e);
        }
    }

    private StoreException fail(final String what, final SQLException e) {
        storeErrors++;
        ThrottledLogger.warn("store-failed-" + what, what + " 落库失败，本条丢弃并计入 sinkErrors：" + e);
        return new StoreException(what + " 落库失败", e);
    }

    /**
     * {@code payload_id} 是唯一允许为 NULL 的列（载荷被拒 / 编码失败）。
     * 用 {@code setNull} 而不是塞一个魔数 —— 读侧才能用 {@code wasNull()} 分清"没有载荷"。
     */
    private static void setNullableLong(final PreparedStatement ps, final int index, final long value)
            throws SQLException {
        if (value == PayloadRing.NO_BLOCK) {
            ps.setNull(index, java.sql.Types.BIGINT);
        } else {
            ps.setLong(index, value);
        }
    }

    private static String nz(final String s) {
        return s == null ? "" : s;
    }

    private static String blankToNull(final String s) {
        return s == null || s.isEmpty() ? null : s;
    }

    private static int positive(final int limit) {
        return limit <= 0 ? 1 : limit;
    }
